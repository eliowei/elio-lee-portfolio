"""Regenerate the self-hosted Noto Sans TC subsets (public/fonts/*.woff2) and app/assets/css/noto-sans-tc.generated.css.

Why: Google Fonts serves CJK as ~15 slices (~1 MB) that all block first paint. Here the font is cut to the characters the
site actually uses, in disjoint unicode-range groups (ui / article / ja), so each page only downloads what it uses.
Run after adding a lot of new text (articles, copy):
    python scripts/subset-font.py <path to NotoSansTC[wght].ttf>
Source font (OFL): https://github.com/google/fonts/raw/main/ofl/notosanstc/NotoSansTC%5Bwght%5D.ttf
Characters missing from the subsets fall back to the system CJK font in the font stacks, so nothing breaks.
Latin is served by Inter / Barlow, so only characters above U+007F are included.
Requires: pip install fonttools brotli
"""
import pathlib, sys
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1])


def chars(globs):
    s = set()
    for g in globs:
        for f in root.glob(g):
            if f.is_file():
                s |= {c for c in f.read_text(encoding='utf8', errors='ignore') if ord(c) > 0x7F}
    return s


# Disjoint groups, so a page only downloads the groups whose characters it actually uses:
#   en      – the few CJK characters in the English copy (e.g. the Chinese name); English pages need only this
#   ui      – interface, home / experience / project data and zh strings (every zh page needs it; the home page needs only this + en)
#   article – characters that only appear in notes / legal pages
#   ja      – characters that only appear in the Japanese copy
en = chars(['app/data/en/*.ts', 'i18n/locales/en.json', 'content/en/**/*.md'])
ui = chars(['app/**/*.vue', 'app/*.vue', 'app/lib/*.ts', 'app/composables/*.ts', 'server/**/*.ts', 'app/data/*.ts', 'i18n/locales/zh.json']) - en
article = chars(['content/blog/*.md', 'content/legal/*.md']) - ui - en
ja = chars(['app/data/ja/*.ts', 'i18n/locales/ja.json', 'content/ja/**/*.md']) - ui - en - article
groups = {'en': en, 'ui': ui, 'article': article, 'ja': ja}
print({k: len(v) for k, v in groups.items()})


def ranges(cs):
    cps = sorted(ord(c) for c in cs)
    out, i = [], 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1:
            j += 1
        out.append(f'U+{cps[i]:X}' if i == j else f'U+{cps[i]:X}-{cps[j]:X}')
        i = j + 1
    return ', '.join(out)


css = ['/* Generated by scripts/subset-font.py — do not edit. */']
for name, cs in groups.items():
    for wght in (400, 700):
        font = instancer.instantiateVariableFont(TTFont(src), {'wght': wght})
        sub = subset.Subsetter(subset.Options(layout_features=['*'], notdef_outline=True, name_IDs=['*']))
        sub.populate(text=''.join(sorted(cs)))
        sub.subset(font)
        font.flavor = 'woff2'
        out = root / f'public/fonts/noto-sans-tc-{name}-{wght}.woff2'
        font.save(out)
        print(out.name, out.stat().st_size // 1024, 'KB')
        css.append(f"@font-face {{ font-family: 'Noto Sans TC'; font-style: normal; font-weight: {wght}; font-display: swap; src: url('/fonts/{out.name}') format('woff2'); unicode-range: {ranges(cs)}; }}")
(root / 'app/assets/css/noto-sans-tc.generated.css').write_text('\n'.join(css) + '\n', encoding='utf8')
