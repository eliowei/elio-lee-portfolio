"""Download Google Fonts (Latin only) + the Material Symbols icon subset into public/fonts and write
app/assets/css/latin-fonts.generated.css, so the site loads no external font CSS.

Run when you add an icon name or change families/weights:   python scripts/fetch-fonts.py
Icons: every icon name used anywhere must be listed in ICONS (alphabetical order is applied below). A missing name shows
as plain text.   Requires: pip install fonttools brotli   (only to convert TrueType -> woff2 if Google serves it)
"""
import io, pathlib, re, urllib.request
from fontTools.ttLib import TTFont

root = pathlib.Path(__file__).resolve().parent.parent
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'
ICONS = ('accessibility_new api arrow_back arrow_forward arrow_outward arrow_upward assignment_turned_in auto_stories brush build check '
         'check_circle chevron_left chevron_right close code compare content_copy devices domain email error expand_more explore fact_check '
         'format_quote group_work groups hub language layers mail map markunread_mailbox menu message pedal_bike person_search school search '
         'send shield south sports_esports storefront task_alt topic travel_explore troubleshoot web').split()
URLS = [
    'https://fonts.googleapis.com/css2?family=Geist:wght@400..700&family=Geist+Mono:wght@400;500&family=Inter:wght@400..600&display=swap',
    'https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,300..500,0,0&icon_names=' + ','.join(sorted(ICONS)) + '&display=swap',
]


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA})).read()


out_css = ['/* Generated by scripts/fetch-fonts.py — do not edit. */']
for u in URLS:
    css = get(u).decode()
    # blocks are "/* subset */ @font-face { ... }"; keep latin (icons have no subset comment) and skip the rest
    for label, block in re.findall(r'(?:/\* ([\w-]+) \*/\s*)?(@font-face \{.*?\})', css, re.S):
        if label and label != 'latin':
            continue
        fam = re.search(r"font-family: '([^']+)'", block).group(1)
        wght = re.search(r'font-weight: ([\d ]+);', block).group(1).strip()
        src = re.search(r'url\(([^)]+)\) format\(\'(\w+)\'\)', block)
        data = get(src.group(1))
        name = f"{fam.lower().replace(' ', '-')}-{wght.replace(' ', '-')}.woff2"
        if src.group(2) != 'woff2':
            f = TTFont(io.BytesIO(data)); f.flavor = 'woff2'; buf = io.BytesIO(); f.save(buf); data = buf.getvalue()
        (root / 'public/fonts' / name).write_bytes(data)
        print(name, len(data) // 1024, 'KB')
        block = block.replace(src.group(0), f"url('/fonts/{name}') format('woff2')")
        out_css.append(re.sub(r'\s+', ' ', block))
(root / 'app/assets/css/latin-fonts.generated.css').write_text('\n'.join(out_css) + '\n', encoding='utf8')
